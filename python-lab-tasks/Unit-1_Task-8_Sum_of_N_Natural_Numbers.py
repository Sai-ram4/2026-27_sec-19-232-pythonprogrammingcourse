 # input my number
my_number = int(input("Enter a number: "))
# check the data type of the input
print("The data type of the input is:", type(my_number))
# convert the number to a string
my_number_str = str(my_number)
# check the data type of the converted string
print("The data type of the converted string is:", type(my_number_str))
# convert the string back to an integer
my_number_int = int(my_number_str)
# check the data type of the converted integer
print("The data type of the converted integer is:", type(my_number_int)) 